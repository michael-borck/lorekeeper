"""Ed25519 signing helpers for packs."""

from __future__ import annotations

import base64
import hashlib
import os
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

DEFAULT_PRIVATE = Path.home() / ".lorekeeper" / "lorekeeper-signing.pem"
DEFAULT_PUBLIC = Path.home() / ".lorekeeper" / "lorekeeper-public.txt"


def load_private_key(path: Path) -> Ed25519PrivateKey:
    key = serialization.load_pem_private_key(Path(path).read_bytes(), password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError("The signing key is not an Ed25519 private key.")
    return key


def public_bytes(key: Ed25519PrivateKey) -> bytes:
    return key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )


def key_id(key: Ed25519PrivateKey) -> str:
    return hashlib.sha256(public_bytes(key)).hexdigest()[:16]


def public_key_b64(key: Ed25519PrivateKey) -> str:
    return base64.b64encode(public_bytes(key)).decode("ascii")


def sign_bytes(key: Ed25519PrivateKey, data: bytes) -> str:
    return base64.b64encode(key.sign(data)).decode("ascii")


def keygen(
    private_path: Path = DEFAULT_PRIVATE,
    public_path: Path = DEFAULT_PUBLIC,
    trusted_path: Path | None = None,
    force: bool = False,
    append: bool = False,
) -> str:
    private_path = Path(private_path).expanduser()
    public_path = Path(public_path).expanduser()
    if private_path.exists() and not force:
        raise FileExistsError(f"signing key already exists: {private_path}")
    private_path.parent.mkdir(parents=True, exist_ok=True)
    key = Ed25519PrivateKey.generate()
    private_path.write_bytes(
        key.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
    )
    os.chmod(private_path, 0o600)
    public_path.parent.mkdir(parents=True, exist_ok=True)
    public_path.write_text(public_key_b64(key) + "\n", encoding="utf-8")
    if trusted_path:
        trusted_path = Path(trusted_path)
        trusted_path.parent.mkdir(parents=True, exist_ok=True)
        entry = f'  "{key_id(key)}": "{public_key_b64(key)}",\n'
        if append and trusted_path.exists():
            text = trusted_path.read_text(encoding="utf-8")
            if key_id(key) not in text:
                if "};" in text:
                    text = text.replace("};", entry + "};", 1)
                else:
                    text += entry
                trusted_path.write_text(text, encoding="utf-8")
        else:
            trusted_path.write_text(
                "// Generated by `lorekeeper keygen`. Public keys only.\n"
                "window.LOREKEEPER_TRUSTED_KEYS = {\n"
                f"{entry}"
                "};\n",
                encoding="utf-8",
            )
    return key_id(key)
