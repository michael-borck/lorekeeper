"""Build a standalone static site for GitHub Pages or any static host."""

from __future__ import annotations

import shutil
from pathlib import Path

from .compile import compile_all
from .registry import engine_root

REDIRECT = """<!doctype html>
<html lang="en-AU">
<head>
  <meta charset="utf-8">
  <meta http-equiv="refresh" content="0; url=./player/">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Lorekeeper</title>
  <link rel="canonical" href="./player/">
</head>
<body>
  <p><a href="./player/">Open Lorekeeper</a></p>
</body>
</html>
"""

SITE_README = """# Lorekeeper site

Generated by `python3 -m lorekeeper site`. Do not edit this branch by hand.

Source and authoring tools: https://github.com/michael-borck/lorekeeper
"""

IGNORE = shutil.ignore_patterns("._*", ".DS_Store", "__pycache__", "*.pyc")


def build_site(out: Path, cname: str | None = None) -> Path:
    out = out.resolve()
    root = engine_root().resolve()
    if out == root or root.is_relative_to(out):
        raise ValueError(f"refusing to write the site into {out}")

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    compile_all(out / "build")
    shutil.copytree(root / "player", out / "player", ignore=IGNORE)

    (out / "index.html").write_text(REDIRECT, encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    (out / "README.md").write_text(SITE_README, encoding="utf-8")
    if cname:
        (out / "CNAME").write_text(f"{cname.strip()}\n", encoding="utf-8")

    for extra in out.rglob("._*"):
        extra.unlink()
    return out
